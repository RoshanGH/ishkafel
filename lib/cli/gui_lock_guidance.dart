import '../core/storage/task_lock.dart';

/// 写不进去时该跟 Agent 说什么。**只此一处**，三个命令共用。
///
/// 原来三处各写一句「等它结束，或在 app 里强制接管」。验收 Agent 的原话：
///
/// > 错误信息本身在教我去点界面。这句话对一个纯 CLI 的 Agent 是死路：
/// > 它给出的唯一出路在界面上。
///
/// 而且这时候占着锁的「人」往往就是 Agent 自己叫出来的——`ui new-task`
/// 建完会把界面停在新任务的编导台上，于是它被自己刚建的任务锁在门外，
/// 手册还说「别硬重试、去问人」，根本没有人。它只能靠试错摸出
/// 「把界面挪到别的任务上」这一招。
///
/// 所以这里按占锁的是谁分开说，并且**给出命令行走得通的出路**。
String guiLockGuidance({required String? holder, required String taskId}) {
  if (isGuiHolder(holder)) {
    return '这个任务的页面正开着（$holder），界面占着它，命令写不进去。\n'
        '两条路：\n'
        '· 让界面挪开：ishkafel open <另一个任务 id>——'
        '页面一离开，锁就放了，再跑一次这条命令就成\n'
        '· 人正在上面编辑的话，等他退出来。'
        '注意：`ui new-task` 建完会把界面停在新任务上，'
        '所以这个「占着的人」很可能就是你自己刚叫出来的';
  }
  return '${holder ?? '别人'} 正在操作这个任务，写不进去。'
      '这是另一个程序占着，把界面挪开没用——等它结束，或者问用户';
}
