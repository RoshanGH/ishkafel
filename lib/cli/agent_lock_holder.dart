import 'dart:io';

/// Agent 占锁时的名字。**只有这一份**。
///
/// 带上 pid 是必须的：锁失效除了心跳超时（60 秒），还有一条快捷判据是
/// 「写锁的进程还在不在」——命令被杀、崩掉之后，人能立刻接手而不是干等
/// 一分钟。而那条判据要靠名字里的 pid 才认得出来。
///
/// 这个名字原本散在十几处、各写各的（`agent` / `Agent` 都有），
/// 全都不带 pid，于是那条判据对 Agent 的锁完全无效
/// （真机自查：导出命令被杀之后锁还躺着）。
final String agentLockHolder = 'agent:$pid';
