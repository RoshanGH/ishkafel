## 交给人审核

**挑完候选不要直接导出。** 你挑的素材需要人过目——这是这条流水线里
人把关的一环，跳过它等于替用户拍板。两条路：

**① 快速把关（推荐）：`ishkafel review <task>`**

前提是你已经 `apply plans` 提交过方案——提交那一刻方案会**投影成任务的
替换现状**（`task` 输出里的 `replacements` 字段），审核页读的就是它。

弹出专门的审核界面：你挑的每条候选和原片对照摆开，人悬停播放、点击剔除、
一次确认。确认那一刻剔除落进 `replacements`——它是主流程的唯一真相。

**然后等用户发话。** 人审完会告诉你「审核完了，继续」。等不等、等多久、
超时怎么办，是你和用户之间约定的策略（比如用户说「一分钟没回你就直接导」），
软件不当流程裁判。

**剔了哪几条**：跑 `ishkafel task <task>` 看 `replacements`——你提交过的
素材 id 不在里面了，就是被人剔掉的。被剔除说明人不认可那一类选择——
**更新方案换掉它们再导**，不要把刚被剔掉的又换个 id 提上来。

**导出会替你把这道关**：方案里还引用着被剔除素材就跑 `export`，那条方案
会被点名拦下（退出码 2）——绝不会把人剔掉的素材静默导出去。

**人在审核台上指挥你剔除**：这是最常见的用法——人看着卡片墙说「第 3、
7、12 条删掉」，你去删。三条命令：

```bash
ishkafel review list <task>                      # 先看有哪些，带编号
ishkafel review drop <task> --items 0:-:100,1:2:202
ishkafel review keep <task> --items 0:-:100      # 剔错了恢复回来
```

编号是 `单元:镜头:素材`，整体替换的候选镜头位写 `-`；`list` 返回的 `ref`
可以原样喂回去，不用自己拼。**编号写错整批不落盘**并一次点名全部问题——
不会出现「以为删了三条实际删了一条」。

**人正开着审核页时，这两条命令走委派**：不是你写盘，是界面替你点。因为
审核页上剔掉的卡只是界面里的临时状态，**人按「确认」才落盘**——你绕过界面
写盘会让人还没确认盘上就变了。这时返回的 JSON 里 `delegated: true`，
**要如实转告人「已经标好了，按确认才生效」**，别报成「已删除」。

**互斥**：另一个 Agent 占着任务时你的写入会返回退出码 4——等它。
人开着界面**不算冲突**（上面那条委派路径），但人在工作台深度编辑时
`apply` / `export` 仍会返回 4。

**② 深度编辑：`ishkafel open <task>`**

把 app 弹出来落到完整工作台。人在那里能预览、能改切分、能换素材、能自己
导出。适合人要亲自动手调的场合；只是过目用 ①，别把人扔进编辑器。

**注意锁**：你在操作时任务是锁着的，人打开会看到只读横幅**并跟着你走**
（不是一张空白拦截页——人正是为了看你干活才打开的）；人可以强制接管，
之后你的写入会被拒绝。反过来，人正开着工作台时你的 `apply` / `export` 会返回
退出码 `4`——等它，或者让人先关掉。

锁会在持有者停止心跳 60 秒后自动失效，所以不会有永久卡死。

