# 脚本成片：给 Agent 的干活手册

## 零、先选模式：静默还是当着人的面干

这不是技术开关，是两种完全不同的场景，**开工前先弄清楚人要哪一种**：

| | 什么时候用 | 会发生什么 |
|---|---|---|
| **静默**（默认） | 人不在场，让你跑完看结果 | 不弹窗、不导航，快就是好 |
| **可视**（`--visual` 或 `ISHKAFEL_VISUAL=1`） | 人说「我要看着你做」 | 软件自己弹出来，你动哪一行界面就滚到哪一行，你开哪个面板界面就打开哪个 |

```bash
ISHKAFEL_VISUAL=1 ishkafel script apply shots <任务> --file p.json
```

可视模式下**每一步会等界面真的展示完**（滚动停下、面板展开）才继续——
节奏由界面决定，不是你猜时间。界面没开着就等一下自动往下跑，不会卡住。

人这时候点不动软件（两边同时写会互相覆盖），但他随时能在你这头喊停：
**Ctrl+C 一按你就要立刻放手**（命令自己会撤锁），他可能要自己上手改一改，
改完再让你接着看。这就像有人站在你旁边看你干活——他叫停，你手就得拿开。



> CLI 只提供**事实与保护**，怎么干得好靠这份文档。没有它，那些命令只是一堆
> 能调用的动作，产不出能用的片子。

## 一、这件事在做什么

编导手里有一条**参考片**（别人的成片），他想用自己素材库里的画面把它复刻一遍：
台词照着念（换成合成配音）、画面换成妙啊素材库里像的镜头、字幕重新断句、
配上音乐，导出成片。

所以你的一切判断都围绕一句话：**这一镜要复刻的是参考片的哪个画面。**

## 一点五、从零到一条片子

```bash
ishkafel script new "8月新品口播"                    # 建任务
ishkafel script extract <任务> ~/参考片.mp4          # 识别台词，生成脚本行
ishkafel script tag-ref <任务> --line N             # ★ 给参考镜打标（有参考片时必做）
ishkafel script apply baseline <任务> --file b.json # ★ 先定本片音色，再配音
ishkafel script voice <任务>                        # 给所有句子配音
# …挑镜头、断句、分时长、配乐（见下文）…
ishkafel script export <任务>                       # 导出成片
ishkafel script jianying <任务>                     # 或者：交给剪映自己精修
```

手写脚本（没有参考片）就跳过 extract，用 `apply lines` 一行行写。

**★ 那一步不能省**：`show` 里 `defaultVoiceId` 是 null 就说明这个片子还没定
音色。这时直接 `voice` 会拿系统默认音色去配全片——不对就白烧一轮 TTS，
而且人还得再等一轮重配。**没定过就先问人要哪个音色**，别自己挑一个：

```bash
ishkafel voices                                   # 列出可选音色（id/名字/场景）
ishkafel script apply baseline <任务> --file b.json  # {"voiceId": "..."}
```

### 写不进去（退出码 4）怎么办

`ui new-task` 建完会**把界面停在新任务上**，于是那个任务被界面占着，
你紧接着的第一条写入就会被拒——「占着的人」其实是你自己刚叫出来的。

出路是把界面挪开：

```bash
ishkafel open <另一个任务 id>     # 页面一离开，锁就放了
```

然后原样重跑刚才那条命令。**不要去点界面上的「强制接管」**——
那是给人用的按钮。

## 一点六、这个片子听起来是什么样

三件事，**分清楚各自的作用范围**：

```bash
# ① 本片基调：行上没单独设的都跟着它走。新加的行也跟着
ishkafel script apply baseline <任务> --file b.json
#    {"voiceId": "云希", "speechRate": 25}
#    默认会同时清掉各行单独设过的（真正统一全片）。
#    只想改基调、保留各行的单独设定，加 {"unify": false}

# ② 某几行单独改：其他行不受影响
ishkafel script apply line-voice <任务> --file v.json
#    {"lines": [{"lineIndex": 2, "voiceId": "晓晓"},
#               {"lineIndex": 5, "speechRate": 50}]}

# ③ 三条声音轨的总音量
ishkafel script apply mix <任务> --file m.json
#    {"sound": {"bgm": 0.4, "sourceMuted": true}}
#    只给要动的那几项，其余保持现状
```

**三条轨是什么**（`show` 里的 `sound`）：

| 轨 | 是什么 |
|---|---|
| `source` 原声 | 素材视频**自己带的**声音：喷雾声、模特原话、环境音 |
| `voice` 口播 | TTS 念你写的台词 |
| `bgm` 配乐 | 背景音乐 |

`duckSourceUnderVoice` 是「有口播的段落把原声压到 `duckedSourceVolume`」——
原声和口播叠在一起是两份声音，默认压到 0。

逐镜的原声音量走 `apply shot-edit` 的 `volume`（相对值，乘在 `sound.source` 上）。

**改完音色或语速，已经生成的配音就过期了**：`show` 里那几行的
`voice.state` 会变成 `stale`。**必须重新 `voice` 一遍再导出**——不然成片里
前几句是旧音色、后几句是新的，人一听就是两个人在说话。

## 你能拿到的信息，和坐在软件前的人一样多

这是这套工具的设计原则，也是你该有的姿态：

> 想还原一个熟手的操作，先得让你**拥有他拥有的全部信息**。
> 人给你派活的时候，你才能拿着足够的信息跟他的目标对齐。

所以：**凡是人在界面上看得见、听得着的，你都能拿到本地文件**。

| 人在界面上 | 你用什么拿 |
|---|---|
| 看参考片这一镜长什么样 | `script frames --line N` 的 `reference[].framePath` |
| 看自己挑的这一镜长什么样 | 同上的 `picked[].framePath`（**成片里真正出现的那一帧**） |
| 点开某条候选看看 | `script peek --materials <id>` |
| 听这一句配音 | `script show --line N` 的 `voice.audioPath` |
| 看整片 | 导出后的成片路径 |

**看图不是锦上添花，是这一步的主要依据。** 画面里的很多东西（光线、
动作、镜头运动、素材自带的字）用文字描述不出来，而它们恰恰决定「这一镜
对不对」。

### 人说「这一镜不对」的时候

别急着换个关键词重搜。先：

```bash
ishkafel script frames <任务> --line 3
```

把**要复刻的目标**（`reference[].framePath`）和**现在的结果**
（`picked[].framePath`）两张图都打开看，找出差在哪，再问人一句
「你是嫌画面太暗，还是这个动作不对，还是产品露出不够？」——
**拿着图跟他确认方向，再去搜**。

瞎猜着重搜的代价很实在：真机上有一次连搜三轮，回来的全是别的品牌。

## 二、先看清楚，再动手

```bash
ishkafel script show <任务> --json
```

这是你的全部事实来源。开工前必看三处：

- **`blocking`**：会拦下预览与导出的问题。**干完活要回来再看一次，必须是空的**，
  否则这个片子导不出来
- **`lines[].voice.hasWordTimings`**：false 表示这句配音没有逐字时间，
  **断不了句**（`apply subtitles` 会拒绝你）
- **`lines[].shortfallMs`**：正数表示这一行的画面还没铺满

## 三、挑镜头

### ★ 先给参考镜打标，否则你等于蒙着眼睛挑

`script extract` 只出**台词和切点**。参考镜的画面描述、标签、首帧图
**全是空的**，而挑镜头的三条路都靠它们。所以从参考片复刻时，第一件事是：

```bash
ishkafel script tag-ref <任务> --line 3
```

打完这一行的参考镜才会有 `description` / `tags` / `framePath`。
**打标每镜一次识图、是花钱的一步**，所以按行打、打过的自动跳过。

不打就挑镜头会怎样：`framePath` 是 null（看不见画面）、`--by tags` 没标签
可用、缺省的 `--by content` 没有描述可搜——你只能自己去猜关键词，
猜偏一点就搜回一堆别的品牌的素材。

**这一步是你的活，不是软件的活。** 软件的「自动铺一版」只会照着参考镜的
画面描述去搜——它看不懂视频。你能看懂：参考镜的画面、标签、那一段在说什么，
你都拿得到，**而且能亲眼看图**。

```bash
ishkafel script shots <任务> --line 3 --json
```

给你的东西：

| 字段 | 是什么 |
|---|---|
| `reference[].description` | 参考片这一镜的画面描述（打标 AI 写的，二手） |
| `reference[].tags` | 这一镜的标签 |
| `reference[].asr` | 这一段原片在说什么 |
| **`reference[].framePath`** | **这一镜的本地首帧图——直接打开看** |
| `slotMs` | 这一行要铺多长 |
| `neighbors` | 前后两镜是什么画面（避免连起来很怪） |
| `usedElsewhere` | 整片已经用过的素材（避免撞车） |
| `candidates[]` | 搜出来的候选 |

**先看 `framePath` 那张图**，再看描述——描述是别人总结的二手信息，
图才是第一手。看完你自己判断该搜什么。

### 五种检索方式，和界面上人能用的一样

```bash
ishkafel script shots <任务> --line 3 --by <方式> [--keyword "…"] [--materials <id>]
```

| `--by` | 靠什么找 | 什么时候用 |
|---|---|---|
| `tags` | 参考镜带过来的标签 | 参考镜打过标时的默认路子 |
| `content`（缺省） | 画面描述 | 自己写一句**画面**去搜（不是台词） |
| **`image`** | **某条素材的画面** | **复刻最该用这个**：手里有一条像的，直接找同类 |
| `voiceover` | 素材自带的口播词 | 找「有人在说这句话」的素材 |
| `name` | 素材名 | 同一批素材常有命名规律 |

**以图搜图是复刻场景的主力**：画面里很多东西用文字说不清楚，
而你手里就有参考镜的图。路子是——先用 `content` 或 `tags` 搜一轮、
`peek` 看图挑出一条最像的，再用它 `--by image` 找出一批同类：

```bash
ishkafel script shots <任务> --line 3 --by image --materials 105378
```

拿不准某几条候选像不像，把它们的画面抽到本地亲眼看：

```bash
ishkafel script peek <任务> --materials 105378,105361
```

返回每条的 `framePath`，打开看图。**按需用**——一条素材几十兆，
先按描述和标签筛一轮，剩下拿不准的再 peek。

这一行**有参考片**时，候选是照着参考镜的画面描述搜来的，可以直接用。

**没有参考片**（手写的脚本）时 `candidates` 会是空的，自己给一句
**画面描述**去搜：

```bash
ishkafel script shots <任务> --line 3 --keyword "一只手在厨房台面上举着喷雾瓶"
```

描述的是**画面**，不是台词。拿台词去搜画面描述是行不通的——
台词是一句话、画面是一幅画，不在一个维度上。


```bash
ishkafel script shots <任务> --line <行号> --json
```

返回里有四样东西，每一样都对应一条判断规则：

### 1. `reference[].description` —— 要复刻的就是它

参考片这一镜长什么样。**这是头号依据**，不是台词。

台词说的是「如果你觉得有点贵」，而画面可能是「一只手在货架前拿起两瓶喷雾」。
拿台词去找画面是错配——软件里曾经这么干过，0.1.45 砍掉了，你别再捡回来。

如果 `hint` 说「参考镜还没打标」，那就是没有依据可用，**先去打标**，
别硬着头皮猜。

### 2. `neighbors` —— 避免「每个都对、连起来不对」

前后两行已经选了什么画面。三句话都是「手持喷雾瓶特写」，单看每句都对，
连起来像卡带。挑之前先看看邻居是什么景别、什么动作。

### 3. `usedElsewhere` —— 避开整片已用的

妙啊里同一批素材常有微调版（1~5 号几乎一样、6~10 又一批）。
撞了同一条，或者撞了同一批的孪生版本，片子看着就像在重复。

### 4. `candidates[].availableMs` vs `slotMs` —— 够不够铺

素材能出的时长要 ≥ 这一行的坑位，不够就得多挑一条来拼。
**不够而硬挑，成片里那一段会定格**。

### 提交

```bash
echo '{"picks":[{"lineIndex":1,"materialIds":[500123]}],"candidates":[…]}' > p.json
ishkafel script apply shots <任务> --file p.json
```

`candidates` 要把 `script shots` 给你的那一份**原样带上**——我们据此核对你选的
东西存不存在、够不够铺。

## 四、断句（这一步你比软件强）

```bash
ishkafel script subtitles <任务> --line <行号> --json
```

软件的自动分屏是「标点优先 → 停顿次之 → 字数兜底」的启发式，本质是在猜。
而断句是**语言判断**，你天然更擅长。切点是词序号，完全可验证——这正是这一步
交给你的原因。

### 规则

1. **一屏是一口气，不是一行字**。按语义停顿断，不要凑字数
2. **数字、金额、单位不能拆**：「69.9 一瓶」不许在小数点或量词处断
3. **一屏别少于 4 个字**：闪一下就过去，看的人只觉得晃眼（会被拒绝）
4. **别超过 `maxCharsPerScreen`**：那是按当前字号算出来的一行能放几个字，
   超了会出画（会被拒绝）
5. **别在画面切换的接缝上换屏**：`shotBoundaries` 给了每一镜的起止时刻。
   一屏正好跨在接缝上，观感是字幕在画面切换那一瞬换了一半。
   **这条是建议不是硬规则**——软件把事实给你，避不避让你判断

### 提交

```bash
echo '{"subtitles":[{"lineIndex":2,"cuts":[8,18,26,35]}]}' > c.json
ishkafel script apply subtitles <任务> --file c.json
```

切点的意思是「**从第几个词另起一屏**」。第 0 屏隐含从头开始，不用写 0。

提交后这一行会标成「已手改」，人在界面上能看到是你断的句，也能一键退回自动。

## 四点二、两个坐标基准，别搞混

| 写法 | 从几开始 | 用在哪 |
|---|---|---|
| `--line N` | **1**（和界面上看到的行号一致） | 命令行参数 |
| `"lineIndex": N` | **0** | 提交的 JSON 里 |
| 报错信息里的「第 N 行」 | **1** | 读错误时 |

传 `lineIndex: 1` 报「第 2 行不存在」不是矛盾——它在用人话说第 2 行。

## 四点三、行有两种类型

`show` 里每行都有 `type`：

- **`voiced`**：有台词，要配音。时间根是配音时长
- **`visual`**：**画面行**，没有台词也没有配音，只有画面。时间根是手填时长

新建的脚本任务自带一个空行，它是 `visual`——**写上台词就自动变成
`voiced`**，不用手动改类型。反过来把台词清空就退回 `visual`。

看到「写了台词但 type 还是 visual」，说明**那次写入没生效**，不是类型没变。

## 四点五、改台词、改镜头、改字幕文字

```bash
ishkafel script apply lines <任务> --file l.json
```

`op` 有三个，语义各不相同：

| op | 干什么 | lineIndex 指的是 |
|---|---|---|
| `set` | 改这一行的台词 | 要改的那一行 |
| `insert` | **在这一行之后插一行新的** | 插在谁后面 |
| `remove` | 删掉这一行 | 要删的那一行 |

```json
{"lines": [
  {"op": "set",    "lineIndex": 0, "text": "改过的台词"},
  {"op": "insert", "lineIndex": 0, "text": "插在第 1 行后面，成为新的第 2 行"},
  {"op": "remove", "lineIndex": 3}
]}
```

**`insert` 是「之后」不是「之前」**：只有 1 行时想追加第 2 行，
写 `lineIndex: 0`（在第 1 行之后）；写 `lineIndex: 1` 会被拒
（那一行还不存在）。

**一批里有多条 insert / remove 时下标会互相影响**——它们是按顺序依次
执行的，前一条插入之后，后面的行都往下挪了一位。稳妥的做法是**一次只
提交一条**，或者从后往前写（下标大的先删）。

删掉带配音的行会连它的配音和镜头一起没，命令会先提醒。

```bash

# 取段、变速、原声音量、删镜
echo '{"shots":[{"lineIndex":2,"shotIndex":0,"op":"volume","value":0.35}]}' > s.json
ishkafel script apply shot-edit <任务> --file s.json

# 某一屏的字幕文字（null = 回到原文，"" = 这屏不出字）
echo '{"screens":[{"lineIndex":2,"screenIndex":0,"text":"改过的字"}]}' > t.json
ishkafel script apply screen-text <任务> --file t.json
```

**改字幕文字有一条硬规矩**：只能改这一屏说了什么，**不能凭空加内容**。
字幕是给念出来的话配的字，与配音对不上就是错的。所以只允许同长或更短——
同音改写、去掉语气词都行，加戏不行。

倍速限定 0.5~2.0：再快听不清，再慢像卡带。

## 四点七、划词建镜（一句话过好几个画面时用这个）

一句话配好几个镜头时，**别自己去猜每一镜多长**。选中台词里的几个字，
那一镜的时长就是这几个字的朗读时长：

```bash
# 1) 先看这一句每个字落在哪、哪些字已经被占住
ishkafel script show <任务> --line 3 --json | jq '{words, takenWords, canPickWords}'

# 2) 给「如果你觉得有点贵」这 8 个字配一个画面
ishkafel script apply word-shots <任务> --file w.json
```

```json
{
  "picks": [{"lineIndex": 2, "startWord": 0, "endWord": 8, "materialId": 105378}],
  "offered": [ ... ishkafel script shots 返回过的候选 ... ]
}
```

**规则（和界面上完全一致）**：

- `startWord` / `endWord` 是**字**的序号，`[起, 止)` 左闭右开。
  `words` 数组的下标就是它——数组里一个元素通常就是一个字
  （数字和英文会并成一个不可拆的整体，比如 `69.91`）
- **已经被占住的字不能再划**（`takenWords` 列出来了）。要改就先用
  `apply shot-edit` 的 `remove` 删掉那一镜，那几个字自动恢复可划
- **可以不连续**：划头、划尾，中间那段留给普通镜头（用 `apply shots` 加）。
  中间不管放几个镜头，加起来永远等于「配音总长 − 各划词镜之和」
- **这一句必须已经有配音**，否则算不出「这几个字读多久」
- 提交的素材必须来自 `script shots` 返回过的候选，不许凭空造 id

**为什么值得用它**：时长是**现算的**，不是存的。换音色、重新配音之后
朗读长短全变，切点不变、时长自动跟上——你不用回头再调一遍。
而且字幕会跟着划词的边界切，画面切到哪儿字幕就换到哪儿。

## 五、分时长

一行分到几个镜头之后，每镜各占多久是创作判断：哪一镜该多停一会儿、
哪一镜一带而过。

**硬约束**：总和必须等于这一行的配音时长（`rootMs`）。差一点点就会让画面与
声音错位——这条软件盯得很死（差 60ms 以上就拒）。

```bash
ishkafel script apply alloc <任务> --file a.json
```

```json
{"alloc": [{"lineIndex": 2, "allocMs": [1280, 2040, 2780, 2780]}]}
```

一行给一组，数组长度要等于那一行的镜头数、总和等于 `rootMs`。

**划词建的镜不用管**：它们的时长是从字区间现算的，你只需要给普通镜头分。
真要改，就改字区间（`apply word-shots` 前先删掉那一镜）。

## 六、配乐

配乐轨的模型是**整片被若干刀切成连续段、铺满全片**，不是「标几段就行」。
提交时所有段首尾相接、覆盖 0 到最后一行，不留空档也不重叠。
某几行不要配乐，也要显式占一段（不给 materialId）。

```bash
ishkafel script bgm-candidates <任务> [--keyword 轻快]   # 先看有哪些曲子
ishkafel script apply bgm <任务> --file b.json
```

```json
{
  "bgm": [
    {"startLine": 0, "endLine": 5, "materialId": 8801, "volume": 0.35},
    {"startLine": 6, "endLine": 9},
    {"startLine": 10, "endLine": 27, "materialId": 8802}
  ],
  "offered": [ ... 候选曲子 ... ]
}
```

中间那段**不给 `materialId` = 这几行不铺配乐**——配乐轨的模型是「整片切成
连续段、铺满全片」，所以「不铺」也要占一段说出来。`volume` 是**相对值**，
乘在配乐轨总音量上（见 `apply mix`）。

`offered` 里填 `bgm-candidates` 返回的 materialId；不铺的那几段不用管。

## 七、读错误

`apply` 是**整批拒绝**，而且一次点全所有问题：

```
这一批没有落盘（整批拒绝，下面是全部问题）：
· 第 2 行的切点 18 超出范围（这句共 9 个字）
· 第 2 行第 2 屏只有 1 个字——闪一下就过去，看的人只会觉得晃眼
```

照着全部改完再提交一次，别改一条试一次。

## 八、人在旁边看着你

你干活时，人的界面会：顶部显示你正在做什么、跟着你的焦点滚动到那一行、
展开你正在动的那一镜。所以：

- **一次做一件事**，别把十行的改动塞进一次提交——人看不清你在干什么
- 干完就收工（命令自己会撤销在场状态），别占着不放

## 八点五、交给剪映

人想自己精修就用这个，不必非得由软件导出成片：

```bash
ishkafel script jianying <任务>
```

把这一版方案写成一份**剪映草稿**：画面段、字幕屏、口播、配乐、素材库全部
就位，素材都落到本地。返回 `draftName`。

**不会替人打开剪映**——剪映没有给外部程序「打开指定草稿」的通道。
所以正确的话术是「草稿已生成，去剪映草稿列表里打开『XXX』」；剪映启动时会
扫一遍（8 秒内认领），运行中每隔几分钟扫一次，没看到让人重启一下剪映。

## 九、收工前

```bash
