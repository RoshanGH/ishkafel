## 两种模式：人在不在旁边看着

这不是技术开关，是两种完全不同的场景。**开工前先弄清人要哪一种**，
然后贯穿整个会话——别中途换。

**静默（默认）**：人不在场。软件被你调起来干活，人回头看结果或直接看成片。
不弹窗、不导航、不等界面——快就是好。

### 不要用 Computer Use / 截图点击

界面上人能做的事，**都有对应的命令**。看到「要打开某个页面、点某个按钮、
填某个表单」时，不要去截图找坐标点击——那样慢、脆、而且人看不出你在干嘛。

这条尤其针对**新建任务**：不要以为「建任务是界面上的事、只能人来点」。
`ishkafel ui new-task` 就会让界面当着人的面把向导打开、填上、创建。

真的遇到没有对应命令的界面操作，**说出来让用户补**，别绕过去。

**可视（`--visual` 或 `ISHKAFEL_VISUAL=1`）**：人在场，而且他要**看着**。
就像站在实习生旁边：

- 软件**自己弹出来**，你开哪个模块界面就切到哪个模块
- 你动哪一行、哪一镜、哪张卡，界面就把它滚到眼前、把那个面板打开——
  跟人自己点开时是同一个面板
- 这期间界面是**只读**的：人不能操作，但**随时能在你这头喊停**
  （Ctrl+C 你就立刻放手，界面马上恢复可操作）
- 节奏由界面定：它真的展示完一步（滚动停下、面板展开）才回执，你收到
  才走下一步。**不要自己猜时间等几百毫秒**

支持可视的命令：`import`、`export`、`script apply`（全部子类）、
`review drop/keep`。人说「你把这个视频复刻一版，我看着」——那就是可视模式。

**新建任务在可视模式下要用 `ui new-task`**：

```bash
# 当着人的面：软件弹出来 → 向导打开 → 来源和标签组填上 → 点创建 → 进任务
ishkafel ui new-task --mode script --tag-groups 1261,1262
ishkafel ui new-task --mode renew  --tag-groups 1261 --file ~/原片.mp4
ishkafel ui new-task --mode blank  --tag-groups 1261
```

`--mode` 就是前面那张表里的两条线（外加旁支 blank）。
参数不合格时**不会弹向导**——让人看着窗口弹出来又关掉，比不弹更糟。

人不在场时用 `script new` / `blank create` / `import` 更快，
那几条在后台直接建好。**但界面开着的话，列表会自己刷新出来**——
不会再出现「命令说建好了、界面上什么都没有」。

**人中途插手了怎么办**：他会在界面上按「我来接手」，你的写入随即被拒
（退出码 4）。这时**停下来问他**，别硬重试——他改了什么只有他知道。

