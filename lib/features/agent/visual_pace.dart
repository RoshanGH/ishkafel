/// 可视化模式的节奏——**全软件只有这一份**。
///
/// 可视化是做给人看的：Agent 一秒能跑完的事，人眼跟不上。每一步都要在
/// 眼前停够久，人才看得清「它现在在干什么」。
///
/// **为什么必须收敛成一处**：这个值原来散在三个地方——播报条要求停
/// 500ms 才回执，编导台等 320ms 就回，工作台也是 320ms。谁先回执 Agent
/// 就走下一步，于是播报条的轮询整步扑空，人看到的是一片空白
/// （真机上分步播报明明写进了盘上，界面一条都没显示出来）。
///
/// 值先定在这儿，按真机观感再调；调的时候只需要改这一行。
const Duration visualStepDwell = Duration(milliseconds: 700);

/// 界面轮询在场状态的间隔。要比 [visualStepDwell] 密得多，
/// 否则一步只在盘上停一瞬就被整个错过
const Duration visualPollInterval = Duration(milliseconds: 200);
